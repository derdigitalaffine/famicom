#!/usr/bin/env python3
"""Exercise a real XMPP STARTTLS + SASL PLAIN login against running Prosody.

This is an *integration smoke test*, not a full XMPP protocol client.
Do not use PLAIN with an untrusted cert in production. CI uses ephemeral TLS.
"""
import base64
import os
import socket
import ssl
import sys
import time
from xml.sax.saxutils import escape

OPEN_STREAM = (
    '<stream:stream to="{domain}" version="1.0" '
    'xmlns="jabber:client" xmlns:stream="http://etherx.jabber.org/streams">'
)

def read_until(connection, wanted, timeout=12):
    result = b""
    expires = time.monotonic() + timeout
    while time.monotonic() < expires and len(result) < 150_000:
        connection.settimeout(min(3, max(.1, expires - time.monotonic())))
        try:
            block = connection.recv(16384)
        except socket.timeout:
            continue
        if not block:
            raise AssertionError("Server closed stream: " + result.decode(errors="replace")[-500:])
        result += block
        if wanted in result:
            return result
        if b"<stream:error" in result:
            raise AssertionError("XMPP stream error: " + result.decode(errors="replace")[-500:])
    raise AssertionError("Missing XMPP response " + wanted.decode() + ": " + result.decode(errors="replace")[-900:])

def attempt(domain, username, password):
    with socket.create_connection(("127.0.0.1", 5222), timeout=10) as plain:
        plain.sendall(OPEN_STREAM.format(domain=escape(domain)).encode())
        initial = read_until(plain, b"</stream:features>")
        assert b"starttls" in initial, "XMPP server did not advertise STARTTLS"
        plain.sendall(b'<starttls xmlns="urn:ietf:params:xml:ns:xmpp-tls"/>')
        proceed = read_until(plain, b"/>")
        assert b"proceed" in proceed, "XMPP STARTTLS not accepted: " + proceed.decode(errors="replace")
        ctx = ssl.create_default_context()
        # Ephemeral certificate generated by bootstrap is intentionally self-signed.
        # Production use MUST validate trusted certificate chains.
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
        with ctx.wrap_socket(plain, server_hostname=domain) as tls:
            tls.sendall(OPEN_STREAM.format(domain=escape(domain)).encode())
            features = read_until(tls, b"</stream:features>")
            assert b"PLAIN" in features, "SASL PLAIN not advertised after TLS"
            auth = base64.b64encode(("\x00" + username + "\x00" + password).encode())
            tls.sendall(b'<auth xmlns="urn:ietf:params:xml:ns:xmpp-sasl" mechanism="PLAIN">' + auth + b"</auth>")
            answer = read_until(tls, b"/>")
            if b"<success" in answer:
                return True
            if b"<failure" in answer:
                return False
            raise AssertionError("Unexpected SASL response: " + answer.decode(errors="replace")[-400:])

if __name__ == "__main__":
    domain = sys.argv[1] if len(sys.argv) > 1 else "family.example.net"
    username = sys.argv[2] if len(sys.argv) > 2 else "admin"
    password = os.environ.get("FAMICOM_TEST_PASSWORD")
    if not password:
        raise SystemExit("FAMICOM_TEST_PASSWORD must be set in CI environment")
    assert attempt(domain, username, password), "Valid XMPP login was rejected"
    assert not attempt(domain, username, password + "-incorrect"), "Invalid XMPP password accepted"
    print("XMPP smoke test passed: valid SASL login accepted, invalid password rejected")
